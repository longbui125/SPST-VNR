const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const P = require('../progress.js');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../content.js'), 'utf8'), sandbox);
const chapters = JSON.parse(JSON.stringify(sandbox.window.SU_DANG_DATA.chapters));
const questions = chapters.flatMap(c => c.questions), q = questions[0];
const memory = new Map();
const storage = { getItem: k => memory.get(k) || null, setItem: (k, v) => memory.set(k, v) };
const a = P.profile('An'), b = P.profile('Bình');
a.lastChapter = 'c3'; a.lastTab = 'map';
a.learned = [chapters[0].mindmap.branches[0].id + '-0'];
assert.equal(P.stats(a, questions).percent, 0);
P.record(a, q, (q.answer + 1) % 4);
assert.equal(P.stats(a, questions).wrong, 1);
P.record(a, q, q.answer);
assert.equal(P.stats(a, questions).correct, 1);
assert.equal(P.stats(a, questions).answered, 1);
assert.equal(a.answers[q.id].attempts, 2);
assert.equal(P.stats(b, questions).answered, 0, 'Profiles must remain isolated');
const state = { version: 1, active: b.id, profiles: [a, b] };
assert(P.save(storage, state));
const restored = P.load(storage, chapters);
assert.equal(restored.state.active, b.id);
assert.equal(restored.state.profiles[0].answers[q.id].attempts, 2);
assert.equal(restored.state.profiles[0].lastChapter, 'c3');
assert.equal(restored.state.profiles[0].lastTab, 'map');
assert.equal(restored.state.profiles[0].learned.length, 1);
assert.equal(P.stats(restored.state.profiles[1], questions).answered, 0);
const imported = P.importProfile(JSON.stringify({ app: 'su-dang', version: 1, profile: a }), chapters);
assert.notEqual(imported.id, a.id, 'Import must create a new profile, never overwrite');
assert.equal(imported.answers[q.id].correct, true);
const tampered = JSON.parse(JSON.stringify(a));
tampered.answers[q.id].selected = (q.answer + 1) % 4;
assert.equal(P.cleanProfile(tampered, chapters).answers[q.id].correct, false, 'Recompute correctness from answer key');
tampered.answers[q.id].selected = 12;
assert.throws(() => P.cleanProfile(tampered, chapters));
assert.throws(() => P.importProfile('{"app":"other","version":1}', chapters));
assert.throws(() => P.importProfile('{bad json', chapters));
assert.equal(P.save({ setItem() { throw Error('quota'); } }, state), false);
a.bookmarks = [q.id]; a.cursors = { [chapters[0].id]: q.id }; a.readerPage = 222;
const before = JSON.stringify(state), cleared = P.reset(a);
assert.equal(JSON.stringify(state), before, 'Preparing a reset must not mutate stored or active state');
for (const field of ['id','name','createdAt']) assert.equal(cleared[field], a[field], 'Keep profile identity');
assert.deepEqual(cleared.answers, {}); assert.deepEqual(cleared.bookmarks, []); assert.deepEqual(cleared.learned, []); assert.deepEqual(cleared.cursors, {});
assert.equal(cleared.readerPage,35); assert.equal(cleared.lastChapter,'c1'); assert.equal(cleared.lastTab,'overview');
assert.equal(P.stats(cleared,questions).answered,0);
P.record(b,q,q.answer);
const afterReset = {...state,profiles:[cleared,b]};
assert(P.save(storage,afterReset));
const reloaded = P.load(storage,chapters).state;
assert.equal(P.stats(reloaded.profiles[0],questions).answered,0,'Reset survives reload');
assert.equal(P.stats(reloaded.profiles[1],questions).correct,1,'Other profiles retain their progress');
const failingStorage = {setItem(){throw Error('quota');}};
assert.equal(P.save(failingStorage,afterReset),false);
assert.equal(P.stats(a,questions).correct,1,'Failed save leaves the original profile available');
storage.setItem(P.KEY, '{corrupt');
assert(P.load(storage, chapters).warning);
assert.equal(storage.getItem(P.KEY + '.unreadable-backup'), '{corrupt', 'Keep unreadable data before fresh state');
assert.throws(() => P.record(b, q, -1));
console.log('PASS: answer/retry, isolated profiles, persistence, confirmed-profile reset, export/import, corruption backup and invalid input.');
